REG_VALUE = "donation_shown"


def xor_utf16(s, k):
    # All content is BMP (emoji + accents + CJK + arabic + devanagari +
    # cyrillic) -> code point == UTF-16 code unit. Valid here.
    return [ord(c) ^ ((k + i) & 0xFFFF) for i, c in enumerate(s)]


def emit(name, s, out):
    units = xor_utf16(s, KEY)
    hexs = ", ".join("0x%04X" % u for u in units)
    out.append(f"constexpr uint16_t {name}[{len(units)}] = {{{hexs}}};")
    out.append(f"constexpr size_t {name}Len = {len(units)};")
    out.append("")


out = []
out.append("// donate_strings.h - GENERATED by tools/gen_donate.py. DO NOT edit by hand.")
out.append("// XOR-encrypted (UTF-16) strings for the donation popup in 8 languages.")
out.append("// Plaintext does not exist in the binary.")
out.append("#pragma once")
out.append("#include <cstddef>")
out.append("#include <cstdint>")
out.append("namespace donate {")
out.append("inline void wdec(const uint16_t* in, size_t n, uint16_t k, wchar_t* out) {")
out.append("    volatile uint16_t vk = k;")
out.append("    for (size_t i = 0; i < n; ++i)")
out.append("        out[i] = static_cast<wchar_t>(in[i] ^ static_cast<uint16_t>(vk + i));")
out.append("    out[n] = L'\\0';")
out.append("}")
out.append("")

for lang in LANGS:
    out.append(f"// ---- {lang} ----")
    emit(f"kMsg_{lang}", MSG[lang], out)
    emit(f"kTitle_{lang}", TITLE[lang], out)

out.append("// ---- pix (pt, Brazil only) ----")
