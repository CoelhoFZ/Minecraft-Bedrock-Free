emit("kPixTitle", PIX_TITLE, out)

out.append("// ---- url / registro ----")
emit("kUrl", URL, out)
emit("kRegPath", REG_PATH, out)
emit("kRegValue", REG_VALUE, out)

out.append("}  // namespace donate")
out.append("")
print("\n".join(out))
