// stub_loader.cpp - layer 1 of the 2-stage packer (inside winmm.dll).
//
// Harden architecture (2 stages - the mapper does NOT exist readable
// anywhere):
//
//   [winmm.dll (plaintext)]  = winmm proxy + STUB (this file)
//   [BLOB1 (encrypted)]      = mapper: decrypts and maps the payload
//   [BLOB2 (encrypted)]      = payload: the shim (QueryApiImpl hook)
//
// winmm only contains: stub + generic loader (miniloader.h). No payload key,
// no name, no mechanism - the "secret sauce" (keys, payload CRC, internal
// overlay layout) lives INSIDE the encrypted BLOB1.
//
// Overlay at the end of winmm (fixed 12-byte trailer):
//   [BLOB2 payload][BLOB1 mapper][u32 size_blob2][u32 size_blob1][u32 magic]
//
// Stub defense layers:
//   1. light anti-debug (IsDebuggerPresent + PEB BeingDebugged) via apihash
//   2. self-check: CRC32 of the .text section of winmm itself (constant in
//      .rdata via volatile - 2-pass build). Patch on the stub = no unlock.
//   3. masked keys in .data (the key plaintext never appears)
//   4. ChaCha20 (RFC 8439) with key+nonce from masked PER-BUILD words
//      (without the key the BLOB does not open; the old LCG opened by the
//      known plaintext 'MZ')
//   5. trailer magic random PER BUILD and masked
//   6. staging buffers zeroed before free (anti-dump)
//   7. WATCHDOG: thread re-checks the .text periodically; if someone
//      patches winmm AFTER load, it flips the kill-switch (the hook stops
//      lying "owned" - game goes back to vanilla without crash).
//   8. ALL APIs via apihash (PEB walk + hash) - the winmm import table does
//      not list VirtualAlloc/ReadFile/etc. (kills the breakpoint on the API
//      that would see the decrypted blob).

